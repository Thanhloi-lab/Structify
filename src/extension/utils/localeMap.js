export const LOCALE_MAP = (() => {
  const fallback = allLocales['en'] ? 'en' : Object.keys(allLocales)[0];
  const out = {};
  for (const [country, localeCode] of Object.entries(mappingCountryToLocaleCode)) {
    out[country] = localeCode;
  }
  return new Proxy(out, {
    get(target, prop) {
      const key = String(prop || '').toUpperCase();
      return target[key] || fallback;
    }
  });
})();